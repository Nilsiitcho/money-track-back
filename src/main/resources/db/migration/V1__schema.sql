-- ===== Usuarios =====
CREATE TABLE app_user (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(100) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- ===== Categorias =====
CREATE TABLE category (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL REFERENCES app_user (id),
    name       VARCHAR(100) NOT NULL,
    archived   BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now()
);
-- Nome unico por usuario (case-insensitive)
CREATE UNIQUE INDEX ux_category_user_name ON category (user_id, lower(name));

-- ===== Lancamentos (regra/definicao) =====
CREATE TABLE entry (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           BIGINT        NOT NULL REFERENCES app_user (id),
    category_id       BIGINT        NOT NULL REFERENCES category (id),
    type              VARCHAR(10)   NOT NULL CHECK (type IN ('RECEITA', 'DESPESA')),
    description       VARCHAR(255)  NOT NULL,
    amount            NUMERIC(12,2) NOT NULL CHECK (amount >= 0),
    recurrence        VARCHAR(12)   NOT NULL CHECK (recurrence IN ('UNICO', 'FIXO', 'PARCELADO')),
    start_month       DATE          NOT NULL,
    end_month         DATE,
    installment_first INT,
    installment_total INT,
    created_at        TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ   NOT NULL DEFAULT now(),
    -- meses sempre no dia 1
    CONSTRAINT ck_entry_start_day1 CHECK (EXTRACT(DAY FROM start_month) = 1),
    CONSTRAINT ck_entry_end_day1   CHECK (end_month IS NULL OR EXTRACT(DAY FROM end_month) = 1),
    CONSTRAINT ck_entry_range      CHECK (end_month IS NULL OR end_month >= start_month)
);
CREATE INDEX ix_entry_user ON entry (user_id);
CREATE INDEX ix_entry_user_months ON entry (user_id, start_month, end_month);

-- ===== Excecoes por mes (editar/excluir "somente este mes") =====
CREATE TABLE entry_override (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entry_id        BIGINT       NOT NULL REFERENCES entry (id) ON DELETE CASCADE,
    reference_month DATE         NOT NULL,
    deleted         BOOLEAN      NOT NULL DEFAULT FALSE,
    type            VARCHAR(10)  CHECK (type IS NULL OR type IN ('RECEITA', 'DESPESA')),
    description     VARCHAR(255),
    amount          NUMERIC(12,2) CHECK (amount IS NULL OR amount >= 0),
    category_id     BIGINT REFERENCES category (id),
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_override_month_day1 CHECK (EXTRACT(DAY FROM reference_month) = 1),
    CONSTRAINT ux_override UNIQUE (entry_id, reference_month)
);
CREATE INDEX ix_override_entry ON entry_override (entry_id);
